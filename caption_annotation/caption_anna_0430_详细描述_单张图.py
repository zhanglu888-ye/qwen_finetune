async def process_image(item, image_data_dict):
    img_path = os.path.join("/host/algorithm4/zhanglu/dataset/vlm/fire/fire_数据标注0425", item["图像名称"])
    image_type = item["图像类型"]
    
    environment_type = item["判断依据"][0].upper()
    risk_type = item["判断依据"][1]+item["判断依据"][2]
    image_fire_anna = '风险代码: ' + risk_type + ', 环境类型: ' + environment_type
    image_infomation = ''
    
    prompt_format = prompt.format(
        image_type=image_type,
        image_infomation=image_infomation,
        image_fire_anna=image_fire_anna,
    )
    result = await llm_util.call_qwen(prompt_format, llm_util.path2base64(img_path))
    print(result)
    # 提取基础名称（去掉_0_first.jpg或_1_second.jpg的部分）
    base_name = item["图像名称"].rsplit('_', 2)[0]
    
    # 将结果存入字典，按基础名称分组
    if base_name not in image_data_dict:
        image_data_dict[base_name] = {
            "visible": None,
            "thermal": None
        }
    
    if "_0_first.jpg" in item["图像名称"]:
        image_data_dict[base_name]["visible"] = {
            "name": item["图像名称"],
            "type": image_type,
            "description": result
        }
    elif "_1_second.jpg" in item["图像名称"]:
        image_data_dict[base_name]["thermal"] = {
            "name": item["图像名称"],
            "type": image_type,
            "description": result
        }
    else:
        # 处理不符合命名规则的图像
        print(f"警告: 图像 {item['图像名称']} 不符合命名规则，将单独保存")
        image_data_dict[item["图像名称"]] = {
            "visible": {
                "name": item["图像名称"],
                "type": image_type,
                "description": result
            } if image_type == "可见光" else None,
            "thermal": {
                "name": item["图像名称"],
                "type": image_type,
                "description": result
            } if image_type == "热成像" else None
        }


async def main():
    # 读取JSON文件
    with open('/host/algorithm4/zhanglu/dataset/vlm/fire/filtered_merged_output_tmp.json', 'r', encoding='utf-8') as f:
        image_data = json.load(f)
    
    # 用于存储分组后的图像数据
    image_data_dict = {}
    
    # 处理每张图片
    for item in image_data:
        await process_image(item, image_data_dict)
    
