def parse_model_output(output_text):
    """
    根据新的模型输出格式，解析出结构化描述、短描述和详细描述。
    
    Args:
        output_text (str): 模型的原始输出字符串。

    Returns:
        tuple: 包含 structured_desc (dict), short_desc (str), detailed_desc (str) 的元组。
    """
    structured_desc = {}
    short_desc = ""
    detailed_desc = ""

    # 1. 提取结构化描述 (JSON部分)
    # 使用正则表达式匹配被 ```json ... ``` 包围的部分
    json_match = re.search(r'```json\s*([\s\S]+?)\s*```', output_text)
    if json_match:
        json_str = json_match.group(1).strip()
        try:
            # 尝试解析JSON字符串
            structured_desc = json.loads(json_str)
        except json.JSONDecodeError as e:
            print(f"解析JSON失败: {e}\n原始JSON字符串: {json_str}")
            # 如果解析失败，仍然保留原始字符串以便调试
            structured_desc = {"error": "JSON a解析失败", "raw_json": json_str}

    # 2. 提取人体短描述
    # 匹配 "### 2. 人体短描述" 之后，到 "### 3. 人体详细描述" 之前的内容
    short_desc_match = re.search(r'### 2\. 人体短描述\s*([\s\S]+?)\s*### 3\. 人体详细描述', output_text, re.DOTALL)
    if short_desc_match:
        short_desc = short_desc_match.group(1).strip()

    # 3. 提取人体详细描述
    # 匹配 "### 3. 人体详细描述" 之后的所有内容
    detailed_desc_match = re.search(r'### 3\. 人体详细描述\s*([\s\S]+)$', output_text, re.DOTALL)
    if detailed_desc_match:
        detailed_desc = detailed_desc_match.group(1).strip()
        
    return structured_desc, short_desc, detailed_desc   


