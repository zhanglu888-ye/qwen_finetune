def parse_txt_file(txt_path):
    """解析txt文件，返回target_person, others_person和things_list"""

    
    target_person = None
    others_person = []
    things_list = []
    
    with open(txt_path, 'r') as f:
        lines = f.readlines()
    
    for i, line in enumerate(lines):
        parts = line.strip().split()
        if len(parts) < 5:
            continue
            
        class_id = int(parts[0])
        x1, y1, x2, y2 = map(float, parts[1:5])
        
        # 格式化坐标信息
        coords = f"{x1:.2f} {y1:.2f} {x2:.2f} {y2:.2f}"
        
        if class_id == 0:
            # 第一个0类作为target_person，其余作为others_person
            if target_person is None:
                target_person = f"人物1 <{coords}>"
            else:
                others_person.append(f"人物{i+1}<{coords}>")
        else:
            # 非0类作为things_list，使用类别名称
            class_name = class_id_to_name.get(class_id, f"未知类别{class_id}")
            things_list.append(f"<{class_name} {coords}>")
    
    # 确保至少有一个target_person
    if target_person is None:
        target_person = "人物1 <0.00 0.00 0.00 0.00>"
    
    # 格式化others_person和things_list
    others_person_str = f"[{', '.join(others_person)}]" if others_person else "[]"
    things_list_str = f"[{', '.join(things_list)}]" if things_list else "[]"
    
    return target_person, others_person_str, things_list_str
